// scripts/migrar-supabase-para-neon.mjs — copia as tabelas do Supabase para o Neon.
//
//   node --env-file=.env scripts/migrar-supabase-para-neon.mjs              só mostra o que seria copiado
//   node --env-file=.env scripts/migrar-supabase-para-neon.mjs --executar   copia de verdade
//   ... --executar --substituir   recria as tabelas no Neon mesmo que já tenham dados
//
// Precisa de SUPABASE_DB_URL e NEON_DB_URL no .env. O Supabase só é lido, nunca alterado.
// As senhas da tabela usuarios são gravadas no Neon como hash bcrypt.
import pg from 'pg';
import bcrypt from 'bcryptjs';

const TABELAS = ['usuarios', 'historico_skus'];
const LOTE = 500;

const executar = process.argv.includes('--executar');
const substituir = process.argv.includes('--substituir');

for (const variavel of ['SUPABASE_DB_URL', 'NEON_DB_URL']) {
  if (!process.env[variavel]) {
    console.error(`Falta ${variavel} no .env`);
    process.exit(1);
  }
}

const conectar = async (url) => {
  const cliente = new pg.Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
  await cliente.connect();
  return cliente;
};

const q = (nome) => `"${nome.replace(/"/g, '""')}"`;

async function lerEstrutura(origem, tabela) {
  const { rows: colunas } = await origem.query(`
    SELECT a.attname AS nome, format_type(a.atttypid, a.atttypmod) AS tipo, a.attnotnull AS obrigatorio,
           a.attidentity AS identidade, pg_get_expr(d.adbin, d.adrelid) AS padrao
    FROM pg_attribute a
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped
    ORDER BY a.attnum`, [`public.${tabela}`]);
  const { rows: restricoes } = await origem.query(`
    SELECT conname AS nome, pg_get_constraintdef(oid) AS definicao
    FROM pg_constraint WHERE conrelid = $1::regclass AND contype IN ('p', 'u', 'c')
    ORDER BY contype DESC`, [`public.${tabela}`]);
  return { colunas, restricoes };
}

// Monta o CREATE TABLE para o Neon. Colunas com sequência viram IDENTITY;
// padrões que dependem de coisas do Supabase (auth.*, extensions.*) são adaptados ou removidos.
function montarCreate(tabela, { colunas, restricoes }) {
  const avisos = [];
  const sequenciais = [];
  const linhas = colunas.map((c) => {
    let def = `${q(c.nome)} ${c.tipo}`;
    let padrao = c.padrao;
    if (c.identidade || (padrao && padrao.startsWith('nextval('))) {
      def += ' GENERATED BY DEFAULT AS IDENTITY';
      sequenciais.push(c.nome);
      padrao = null;
    }
    if (padrao && /uuid_generate_v4\(\)/.test(padrao)) padrao = 'gen_random_uuid()';
    if (padrao && /\b(auth|extensions|storage)\./.test(padrao)) {
      avisos.push(`${tabela}.${c.nome}: padrão "${padrao}" é do Supabase e foi removido`);
      padrao = null;
    }
    if (padrao) def += ` DEFAULT ${padrao}`;
    if (c.obrigatorio) def += ' NOT NULL';
    return def;
  });
  for (const r of restricoes) linhas.push(`CONSTRAINT ${q(r.nome)} ${r.definicao}`);
  return { sql: `CREATE TABLE ${q(tabela)} (\n  ${linhas.join(',\n  ')}\n)`, sequenciais, avisos };
}

async function main() {
  const origem = await conectar(process.env.SUPABASE_DB_URL);
  const destino = await conectar(process.env.NEON_DB_URL);

  try {
    const { rows: todas } = await origem.query(`SELECT tablename FROM pg_tables WHERE schemaname = 'public' ORDER BY 1`);
    const outras = todas.map((t) => t.tablename).filter((t) => !TABELAS.includes(t));
    console.log(`Tabelas no Supabase (schema public): ${todas.map((t) => t.tablename).join(', ') || '(nenhuma)'}`);
    if (outras.length) console.log(`  Atenção: ${outras.join(', ')} não são usadas pelo app e NÃO serão copiadas.`);

    const planos = [];
    for (const tabela of TABELAS) {
      const estrutura = await lerEstrutura(origem, tabela);
      const create = montarCreate(tabela, estrutura);
      const { rows: [{ total }] } = await origem.query(`SELECT count(*)::int AS total FROM ${q(tabela)}`);
      const { rows: [existe] } = await destino.query(`SELECT to_regclass($1) AS oid`, [`public.${tabela}`]);
      let noNeon = null;
      if (existe.oid) noNeon = (await destino.query(`SELECT count(*)::int AS total FROM ${q(tabela)}`)).rows[0].total;
      planos.push({ tabela, estrutura, create, total, noNeon });

      console.log(`\n== ${tabela}: ${total} linha(s) no Supabase` + (noNeon === null ? ', não existe no Neon' : `, já existe no Neon com ${noNeon} linha(s)`));
      console.log(create.sql);
      create.avisos.forEach((a) => console.log(`  Aviso: ${a}`));
    }

    if (!executar) {
      console.log('\nNada foi alterado. Rode com --executar para copiar.');
      return;
    }

    const comDados = planos.filter((p) => p.noNeon > 0);
    if (comDados.length && !substituir) {
      console.error(`\nAs tabelas ${comDados.map((p) => p.tabela).join(', ')} já têm dados no Neon. Use --substituir para apagá-las e copiar de novo.`);
      process.exitCode = 1;
      return;
    }

    await destino.query('BEGIN');
    for (const { tabela, estrutura, create } of planos) {
      await destino.query(`DROP TABLE IF EXISTS ${q(tabela)} CASCADE`);
      await destino.query(create.sql);

      const nomes = estrutura.colunas.map((c) => c.nome);
      const json = new Set(estrutura.colunas.filter((c) => /^jsonb?$/.test(c.tipo)).map((c) => c.nome));
      const { rows } = await origem.query(`SELECT * FROM ${q(tabela)}`);

      let hashes = 0;
      if (tabela === 'usuarios' && nomes.includes('senha')) {
        for (const linha of rows) {
          if (linha.senha && !String(linha.senha).startsWith('$2')) {
            linha.senha = await bcrypt.hash(String(linha.senha), 10);
            hashes++;
          }
        }
      }

      for (let i = 0; i < rows.length; i += LOTE) {
        const lote = rows.slice(i, i + LOTE);
        const valores = [];
        const marcadores = lote.map((linha) => `(${nomes.map((nome) => {
          valores.push(json.has(nome) && linha[nome] !== null ? JSON.stringify(linha[nome]) : linha[nome]);
          return `$${valores.length}`;
        }).join(', ')})`);
        await destino.query(`INSERT INTO ${q(tabela)} (${nomes.map(q).join(', ')}) VALUES ${marcadores.join(', ')}`, valores);
      }

      for (const coluna of create.sequenciais) {
        await destino.query(`SELECT setval(pg_get_serial_sequence($1, $2), COALESCE((SELECT max(${q(coluna)}) FROM ${q(tabela)}), 0) + 1, false)`, [tabela, coluna]);
      }
      console.log(`\n${tabela}: ${rows.length} linha(s) copiada(s)` + (hashes ? `, ${hashes} senha(s) convertida(s) para bcrypt` : ''));
    }
    await destino.query('COMMIT');

    console.log('\nConferência:');
    for (const { tabela, total } of planos) {
      const { rows: [{ copiadas }] } = await destino.query(`SELECT count(*)::int AS copiadas FROM ${q(tabela)}`);
      console.log(`  ${tabela}: Supabase ${total} -> Neon ${copiadas} ${copiadas === total ? 'OK' : 'DIFERENTE!'}`);
      if (copiadas !== total) process.exitCode = 1;
    }
  } catch (erro) {
    await destino.query('ROLLBACK').catch(() => {});
    throw erro;
  } finally {
    await origem.end();
    await destino.end();
  }
}

main().catch((erro) => {
  console.error('\nFalhou, nada foi gravado no Neon:', erro.message);
  process.exit(1);
});
